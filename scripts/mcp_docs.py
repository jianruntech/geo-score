def rd(p):
    return io.open(os.path.join(ROOT, p), encoding="utf-8").read()


def version():
    m = re.search(r'^__version__ = "([^"]+)"', rd("cli/geo_score.py"), re.M)
    if not m:
        sys.exit("mcp_docs: no __version__ in cli/geo_score.py")
    return m.group(1)


def load_server():
    """MCPServer with every tool on: the default surface, whatever filters the environment asks for."""
    for k in list(os.environ):
        if k.startswith("GEO_SCORE_MCP_") or k in ("GEO_SCORE_PY", "GEO_SCORE_WATCH_CONFIG"):
            del os.environ[k]
    cli = os.path.join(ROOT, "cli")
    sys.path.insert(0, cli)
    spec = importlib.util.spec_from_file_location("geo_watch", os.path.join(cli, "geo_watch.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.MCPServer("/nonexistent.json")


def rpc_list(srv, method, key):
    """A list method answered the way a client would see it; None when the server does not offer it."""
    try:
        r = srv.handle({"jsonrpc": "2.0", "id": 1, "method": method, "params": {}})
    except Exception:
        return None
    if isinstance(r, dict) and isinstance(r.get("result"), dict) and isinstance(r["result"].get(key), list):
        return r["result"][key]
    return None


def is_paid(t):
    ann = t.get("annotations") or {}
    desc = (t.get("description") or "").lstrip()
    if desc.startswith("Free"):
        paid = False
    elif desc.startswith("Paid"):
        paid = True
    else:
        # a tool that changes something outside this machine is one that calls a provider
        paid = not ann.get("readOnlyHint", HINT_DEFAULTS["readOnlyHint"]) and ann.get("openWorldHint", HINT_DEFAULTS["openWorldHint"])
    return bool(paid)


def cost_of(t, lang):
    if not is_paid(t):
        return T[lang]["free"]
    props = (t.get("inputSchema") or {}).get("properties") or {}
    return T[lang]["paid_dry"] if (props.get("dry_run") or {}).get("type") == "boolean" else T[lang]["paid"]


def writes_of(t, lang, warn):
    ann = t.get("annotations") or {}
    ro = ann.get("readOnlyHint", HINT_DEFAULTS["readOnlyHint"])
    if ro:
        if t["name"] in WRITES and WRITES[t["name"]]["en"] != "No":
            sys.exit("mcp_docs: %s is marked readOnlyHint but WRITES says it writes; fix one of them" % t["name"])
        return T[lang]["no"]
    if t["name"] in WRITES:
        return WRITES[t["name"]][lang]
    warn("%s is not read-only and has no WRITES entry in scripts/mcp_docs.py" % t["name"])
    return T[lang]["not_ro"]


def hints_of(t, lang):
    ann = t.get("annotations") or {}
    L = T[lang]

    def get(k):
        # (value, marker): the marker flags a hint the server left out, so the MCP default applies
        return (bool(ann[k]), "") if k in ann else (HINT_DEFAULTS[k], "†")
    out = []
    ro, m = get("readOnlyHint")
    if ro:
        out.append(L["read-only"] + m)
    else:
        # destructiveHint only means something for a tool that is not read-only
        de, m2 = get("destructiveHint")
        out.append((L["destructive"] if de else L["non-destructive"]) + m2)
    idem, m = get("idempotentHint")
    if idem:
        out.append(L["idempotent"] + m)
    ow, m = get("openWorldHint")
    if ow:
        out.append(L["open-world"] + m)
    sep = ", " if lang == "en" else "、"
    return sep.join(out), any(x.endswith("†") for x in out)


def args_of(t, lang):
    s = t.get("inputSchema") or {}
    req = set(s.get("required") or [])
    names = list((s.get("properties") or {}).keys())
    if not names:
        return T[lang]["none"]
    return T[lang]["sep"].join("**`%s`**" % n if n in req else "`%s`" % n for n in names)


def render_tools(srv, lang, warn):
    L = T[lang]
    tools = srv.tools()
    rows, any_dag = [L["head"], "|---|:-:|---|---|---|---|"], False
    for t in tools:
        if t["name"] not in LEVEL:
            warn("%s has no LEVEL entry in scripts/mcp_docs.py" % t["name"])
        h, dag = hints_of(t, lang)
        any_dag = any_dag or dag
        rows.append("| `%s` | %s | %s | %s | %s | %s |" % (
            t["name"], LEVEL.get(t["name"], L["none"]), cost_of(t, lang), writes_of(t, lang, warn), h, args_of(t, lang)))
    out = ["<!-- %s -->" % L["gen"], ""] + rows + [""]
    res = rpc_list(srv, "resources/list", "resources") or []
    if res:
        out += [L["resources"] + L["colon"] + L["sep"].join("`%s`" % r["uri"] for r in res) + L["stop"], ""]
    prompts = rpc_list(srv, "prompts/list", "prompts") or []
    if prompts:
        def sig(p):
            a = [("**`%s`**" if x.get("required") else "`%s`") % x["name"] for x in p.get("arguments") or []]
            return "`%s`" % p["name"] + (L["paren"] % L["sep"].join(a) if a else "")
        out += [L["prompts"] + L["colon"] + L["sep"].join(sig(p) for p in prompts) + L["stop"], ""]
    paid = ["`%s`" % t["name"] for t in tools if is_paid(t)]
    spend = L["spend"] % (L["sep"].join(paid[:-1]) + L["and"] + paid[-1] if len(paid) > 1 else paid[0]) \
        if paid else L["spend_none"]
    out.append(L["notes"] + spend + (L["dagger"] if any_dag else ""))
    return "\n".join(out)


def cfg_for(v):
    return {"command": "uvx", "args": ["--from", WHEEL_URL.format(v=v), "geo-score-mcp"]}


def links(v):
    cfg = cfg_for(v)
    compact = json.dumps(cfg, separators=(",", ":"))
    b64 = base64.b64encode(compact.encode("utf-8")).decode("ascii")
    q = urllib.parse.quote
    inner = q(json.dumps(dict({"name": NAME}, **cfg), separators=(",", ":")), safe="")
    return {
        "cursor": "https://cursor.com/en/install-mcp?name=%s&config=%s" % (NAME, q(b64, safe="")),
        "vscode": "https://insiders.vscode.dev/redirect?url=%s" % q("vscode:mcp/install?" + inner, safe=""),
        "insiders": "https://insiders.vscode.dev/redirect?url=%s" % q("vscode-insiders:mcp/install?" + inner, safe=""),
        "lmstudio": "https://lmstudio.ai/install-mcp?name=%s&config=%s" % (NAME, q(b64, safe="")),
    }


def render_install(v, lang):
    L, u = T[lang], links(v)
    cfg = cfg_for(v)
    std = json.dumps({"mcpServers": {NAME: cfg}}, indent=2)
    # keep the args list on one line, as people write it by hand
    std = re.sub(r'"args": \[\s*([^\]]*?)\s*\]',
                 lambda m: '"args": [' + ", ".join(x.strip() for x in m.group(1).split(",")) + "]", std)
    fence = "```"
    return "\n".join([
        "<!-- %s -->" % (L["gen_install"] % v),
        "",
        "[![%s](https://cursor.com/deeplink/mcp-install-dark.svg)](%s)" % (L["cursor_alt"], u["cursor"]),
        "[![%s](https://img.shields.io/badge/VS_Code-Install_Server-0098FF?style=flat-square&logo=visualstudiocode&logoColor=white)](%s)"
        % (L["vscode_alt"], u["vscode"]),
        "[![%s](https://img.shields.io/badge/VS_Code_Insiders-Install_Server-24bfa5?style=flat-square&logo=visualstudiocode&logoColor=white)](%s)"
        % (L["insiders_alt"], u["insiders"]),
        "[![%s](https://img.shields.io/badge/LM_Studio-Install_Server-4338CA?style=flat-square)](%s)" % (L["lms_alt"], u["lmstudio"]),
        "",
        L["buttons_note"] % v,
        "",
        L["cc"],
        "",
        fence + "bash",
        "claude mcp add --scope user %s -- uvx --from %s geo-score-mcp" % (NAME, WHEEL_URL.format(v=v)),
        fence,
        "",
        L["std"],
        "",
        # a plain fence: validate.py rule 2 keeps labelled json blocks out of README and guide/
        fence,
        std,
        fence,
        "",
        L["desktop"],
        "",
        L["source"] % (GIT_PIN + v),
    ])


def replace_block(text, name, body, path):
    begin, end = "<!-- BEGIN MCP:%s -->" % name, "<!-- END MCP:%s -->" % name
    if text.count(begin) != 1 or text.count(end) != 1:
        sys.exit("mcp_docs: %s needs exactly one %s and one %s" % (path, begin, end))
    i, j = text.index(begin) + len(begin), text.index(end)
    if j < i:
        sys.exit("mcp_docs: %s has %s before %s" % (path, end, begin))
    return text[:i] + "\n" + body + "\n" + text[j:]


def main(argv=None):
    ap = argparse.ArgumentParser(description="Regenerate the MCP tool table and install block in the docs.")
    ap.add_argument("--check", action="store_true", help="change nothing; exit 1 when a file is out of date")
    a = ap.parse_args(argv)
    warnings = []
    srv = load_server()
    v = version()
    stale = []
    for path, lang in FILES:
        full = os.path.join(ROOT, path)
        if not os.path.exists(full):
            sys.exit("mcp_docs: %s does not exist" % path)
        old = rd(path)
        new = old
        new = replace_block(new, "tools", render_tools(srv, lang, warnings.append), path)
        new = replace_block(new, "install", render_install(v, lang), path)
        if new != old:
            stale.append(path)
            if not a.check:
                io.open(full, "w", encoding="utf-8", newline="\n").write(new)
    for w in dict.fromkeys(warnings):
        print("mcp_docs: warning: %s" % w, file=sys.stderr)
    if a.check:
        if stale:
            print("mcp_docs: out of date: %s (run python3 scripts/mcp_docs.py)" % ", ".join(stale), file=sys.stderr)
            return 1
        print("mcp_docs: %d files up to date (version %s)" % (len(FILES), v))
        return 0
    print("mcp_docs: %s" % ("rewrote " + ", ".join(stale) if stale else "nothing to change"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
